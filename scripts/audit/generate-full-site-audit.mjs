import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'fs';
import { resolve } from 'path';
import { resolveAuditConfig } from './resolve-config.mjs';

const config = resolveAuditConfig();
const ROOT = config.ROOT;
const outputDir = resolve(ROOT, config.outputDir);
mkdirSync(outputDir, { recursive: true });

function loadJson(filename) {
  const path = resolve(outputDir, filename);
  if (!existsSync(path)) return null;
  return JSON.parse(readFileSync(path, 'utf-8'));
}

const routeInventory = loadJson('route-inventory.json');
const visualAudit = loadJson('visual-audit.json');
const domInventory = loadJson('page-dom-inventory.json');
const a11yAudit = loadJson('accessibility-audit.json');
const contentAudit = loadJson('content-audit.json');
const conversionAudit = loadJson('conversion-audit.json');

const allFindings = [
  ...(visualAudit?.findings || []),
  ...(a11yAudit?.findings || []),
  ...(contentAudit?.findings || []),
  ...(conversionAudit?.findings || []),
];

// Determine audit validity
const navigationErrors = allFindings.filter(f => f.issue === 'navigation-error' || f.issue === 'audit-error');
const serverUnavailable = navigationErrors.length > 0 && navigationErrors.length >= (allFindings.length * 0.5);

let auditValidity = 'valid';
let invalidReason = null;
if (!routeInventory || routeInventory.totalRoutes === 0) {
  auditValidity = 'not_scored';
  invalidReason = 'No routes discovered';
} else if (serverUnavailable) {
  auditValidity = 'not_scored';
  invalidReason = 'Dev server unavailable; navigation errors on majority of routes';
} else if (navigationErrors.length > 0) {
  auditValidity = 'not_scored';
  invalidReason = `${navigationErrors.length} route(s) had navigation/connection errors`;
}

const launchReady = auditValidity === 'valid' && allFindings.filter(f => f.severity === 'critical').length === 0;

const bySeverity = {
  critical: allFindings.filter(f => f.severity === 'critical'),
  high: allFindings.filter(f => f.severity === 'high'),
  medium: allFindings.filter(f => f.severity === 'medium'),
  low: allFindings.filter(f => f.severity === 'low'),
};

const byCategory = allFindings.reduce((acc, f) => {
  acc[f.category] = acc[f.category] || [];
  acc[f.category].push(f);
  return acc;
}, {});

function md() {
  const lines = [];
  const push = (...args) => lines.push(...args);
  const hr = '\n---\n';

  push('# ezLegal.ai Full Site Audit Report');
  push('');
  push(`**Generated:** ${new Date().toISOString()}`);
  push(`**Audit System Version:** 2.1`);
  push(`**Mode:** ${config.mode}`);
  push(`**Base URL:** ${config.baseUrl}`);
  push('');
  push('> This report is auto-generated by the ezLegal.ai audit harness. Findings are evidence-based.');
  push('> Scores are heuristic. Human judgment is required for prioritization.');
  push('');

  if (auditValidity !== 'valid') {
    push('> **[BLOCKED]** ' + (serverUnavailable
      ? 'Dev server unavailable; no content was evaluated. All findings below are navigation errors, not real audit results.'
      : invalidReason));
    push('');
    push(`> **Audit Validity:** ${auditValidity}`);
    push(`> **Reason:** ${invalidReason}`);
    push(`> **Launch Ready:** No`);
    push('');
  } else {
    push(`> **Audit Validity:** valid`);
    push(`> **Launch Ready:** ${launchReady ? 'Yes' : 'No (critical findings exist)'}`);
    push('');
  }

  push(hr);

  // A. Executive Summary
  push('## A. Executive Summary');
  push('');
  push('| Metric | Value |');
  push('|--------|-------|');
  push(`| Total Routes Discovered | ${routeInventory?.totalRoutes || 0} |`);
  push(`| Public Routes Audited | ${routeInventory?.routes?.filter(r => !r.requiresAuth)?.length || 0} |`);
  push(`| Auth-Required Routes | ${routeInventory?.routes?.filter(r => r.requiresAuth)?.length || 0} |`);
  push(`| Total Findings | ${allFindings.length} |`);
  push(`| Critical | ${bySeverity.critical.length} |`);
  push(`| High | ${bySeverity.high.length} |`);
  push(`| Medium | ${bySeverity.medium.length} |`);
  push(`| Low | ${bySeverity.low.length} |`);
  push('');

  if (contentAudit?.summary) {
    push('### Content Health');
    push(`- Average reading grade: **${contentAudit.summary.averageReadingGrade}** (target: <= ${config.contentThresholds.maxFleschKincaidGrade})`);
    push(`- Routes above threshold: ${contentAudit.summary.routesAboveThreshold}`);
    push(`- Jargon instances: ${contentAudit.summary.totalJargonInstances}`);
    push(`- Spanish content routes: ${contentAudit.summary.spanishContentRoutes}`);
    push('');
  }

  if (conversionAudit?.summary) {
    push('### Conversion Health');
    push(`- Routes without above-fold CTA: ${conversionAudit.summary.routesWithoutCta}`);
    push(`- Average trust signals per page: ${conversionAudit.summary.avgTrustSignals}`);
    push(`- Average ethical AI compliance: ${conversionAudit.summary.avgEthicalAIScore}/4`);
    push('');
  }

  push('### Severity Definitions');
  push('| Level | Definition | SLA |');
  push('|-------|-----------|-----|');
  for (const [key, val] of Object.entries(config.severityLevels)) {
    push(`| ${val.label} | ${val.description} | ${val.sla} |`);
  }
  push(hr);

  // B. Route Inventory
  push('## B. Route Inventory');
  push('');
  if (routeInventory) {
    push(`Total: ${routeInventory.totalRoutes} routes`);
    push('');
    push('| Route | ICP | Auth Required |');
    push('|-------|-----|---------------|');
    for (const r of (routeInventory.routes || []).slice(0, 80)) {
      push(`| \`${r.path}\` | ${r.icp} | ${r.requiresAuth ? 'Yes' : 'No'} |`);
    }
  }
  push(hr);

  // C. Page-by-Page Audit
  push('## C. Page-by-Page Audit');
  push('');
  if (domInventory?.pages) {
    for (const page of domInventory.pages.slice(0, 40)) {
      if (!page.inventory) continue;
      const inv = page.inventory;
      push(`### \`${page.route}\``);
      push('');
      push(`- **Title:** ${inv.title || '[missing]'}`);
      push(`- **Meta Description:** ${inv.metaDescription ? inv.metaDescription.slice(0, 120) : '[missing]'}`);
      push(`- **Lang Attribute:** ${inv.lang || '[missing]'}`);
      push(`- **Headings:** ${inv.headings?.length || 0} (H1: ${inv.headings?.filter(h => h.level === 1).length || 0})`);
      push(`- **CTAs:** ${inv.ctas?.length || 0} (above fold: ${inv.ctas?.filter(c => c.isAboveFold).length || 0})`);
      push(`- **Forms:** ${inv.forms?.length || 0} (max fields: ${Math.max(0, ...(inv.forms?.map(f => f.fieldCount) || [0]))})`);
      push(`- **Links:** ${inv.links?.total || 0} (external: ${inv.links?.external || 0})`);
      push(`- **ARIA Elements:** ${inv.ariaElements?.total || 0}`);
      push(`- **Images:** ${inv.images?.total || 0} (missing alt: ${inv.images?.missingAlt || 0})`);
      push(`- **Spanish Content:** ${inv.spanishContent?.hasSpanishContent ? 'Yes' : 'No'}`);
      push(`- **Disclaimers:** ${inv.disclaimers?.length || 0}`);
      push('');

      const pageFindings = allFindings.filter(f => f.route === page.route);
      if (pageFindings.length > 0) {
        push(`**Findings (${pageFindings.length}):**`);
        for (const f of pageFindings.slice(0, 8)) {
          push(`- [${f.severity.toUpperCase()}] [${f.category}] ${f.issue}: ${f.description}`);
        }
        if (pageFindings.length > 8) push(`- ... and ${pageFindings.length - 8} more`);
        push('');
      }
    }
  } else {
    push('*DOM inventory not available. Run `npm run audit:visual` with dev server active.*');
  }
  push(hr);

  // D. ICP-by-ICP Matrix
  push('## D. ICP Coverage Matrix');
  push('');
  for (const icp of config.icpDefinitions) {
    push(`### ${icp.label}`);
    push(`> ${icp.description}`);
    push('');
    push('**Dedicated Routes:**');
    const icpRoutes = (routeInventory?.routes || []).filter(r => r.icp === icp.id);
    if (icpRoutes.length > 0) {
      for (const r of icpRoutes) push(`- \`${r.path}\``);
    } else {
      push('- None dedicated');
    }
    push('');
    push('**Expectations vs. Reality:**');
    push('| Expectation | Status |');
    push('|------------|--------|');
    for (const exp of icp.expectations) {
      const hasEvidence = domInventory?.pages?.some(p =>
        p.icp === icp.id && p.inventory
      );
      push(`| ${exp} | ${hasEvidence ? '[inference] Partially present' : '[evidence unavailable]'} |`);
    }
    push('');

    const icpFindings = allFindings.filter(f => icpRoutes.some(r => r.path === f.route));
    if (icpFindings.length > 0) {
      push(`**Findings affecting this ICP:** ${icpFindings.length}`);
      push('');
    }
  }
  push(hr);

  // E. Cognitive Overload Findings
  push('## E. Cognitive Overload Findings');
  push('');
  push('Assessment based on jargon density, reading level, choice count, form burden, and unclear next steps.');
  push('');

  if (contentAudit?.routeMetrics) {
    const highGrade = contentAudit.routeMetrics.filter(r => r.fleschKincaidGrade > config.contentThresholds.maxFleschKincaidGrade);
    if (highGrade.length > 0) {
      push('### High Reading Complexity');
      push('| Route | Grade Level | Jargon | Long Sentences |');
      push('|-------|-------------|--------|----------------|');
      for (const r of highGrade.sort((a, b) => b.fleschKincaidGrade - a.fleschKincaidGrade).slice(0, 15)) {
        push(`| \`${r.route}\` | ${r.fleschKincaidGrade} | ${r.jargonCount} | ${r.longSentenceCount} |`);
      }
      push('');
    }
  }

  const jargonFindings = allFindings.filter(f => f.issue === 'legal-jargon');
  if (jargonFindings.length > 0) {
    push('### Legal Jargon Instances');
    push('| Route | Term | Context |');
    push('|-------|------|---------|');
    for (const f of jargonFindings.slice(0, 20)) {
      push(`| \`${f.route}\` | ${f.term || ''} | ${f.description?.slice(0, 80) || ''} |`);
    }
    push('');
  }

  const formBurden = allFindings.filter(f => f.issue === 'form-burden');
  if (formBurden.length > 0) {
    push('### Form Burden');
    for (const f of formBurden) {
      push(`- \`${f.route}\`: ${f.description}`);
    }
    push('');
  }

  if (contentAudit?.routeMetrics?.length === 0 && jargonFindings.length === 0) {
    push('*No cognitive overload findings detected or dev server unavailable during audit.*');
    push('');
  }
  push(hr);

  // F. Conversion Optimization Findings
  push('## F. Conversion Optimization Findings');
  push('');

  const convFindings = allFindings.filter(f => f.category === 'conversion');
  if (convFindings.length > 0) {
    push('### CTA Issues');
    const ctaIssues = convFindings.filter(f => f.issue.includes('cta'));
    for (const f of ctaIssues.slice(0, 15)) {
      push(`- [${f.severity.toUpperCase()}] \`${f.route}\`: ${f.description}`);
    }
    push('');

    push('### Trust Signal Gaps');
    const trustIssues = convFindings.filter(f => f.issue.includes('trust'));
    for (const f of trustIssues.slice(0, 10)) {
      push(`- [${f.severity.toUpperCase()}] \`${f.route}\`: ${f.description}`);
    }
    push('');

    const otherConv = convFindings.filter(f => !f.issue.includes('cta') && !f.issue.includes('trust'));
    if (otherConv.length > 0) {
      push('### Other Conversion Issues');
      for (const f of otherConv.slice(0, 10)) {
        push(`- [${f.severity.toUpperCase()}] \`${f.route}\`: ${f.description}`);
      }
      push('');
    }
  } else {
    push('*No conversion findings or dev server unavailable.*');
    push('');
  }

  if (conversionAudit?.routeMetrics) {
    push('### Conversion Metrics Summary');
    push('| Route | CTAs Above Fold | Forms | Trust Signals | Ethical AI Score |');
    push('|-------|-----------------|-------|---------------|-----------------|');
    const relevant = conversionAudit.routeMetrics.filter(r =>
      r.aboveFoldCtas > 0 || r.formCount > 0 || r.ethicalAIScore > 0
    );
    for (const r of relevant.slice(0, 25)) {
      push(`| \`${r.route}\` | ${r.aboveFoldCtas} | ${r.formCount} | ${r.trustSignalCount} | ${r.ethicalAIScore}/4 |`);
    }
    push('');
  }
  push(hr);

  // G. Ethical AI / Access-to-Justice Findings
  push('## G. Ethical AI & Access-to-Justice Findings');
  push('');
  push('Evaluates: AI disclosure, legal advice boundaries, escalation paths, Spanish access, affordability, privacy language, jurisdiction warnings.');
  push('');

  const ethicalFindings = allFindings.filter(f => f.category === 'ethical-ai');
  if (ethicalFindings.length > 0) {
    push('| Severity | Route | Issue | Description |');
    push('|----------|-------|-------|-------------|');
    for (const f of ethicalFindings) {
      push(`| ${f.severity.toUpperCase()} | \`${f.route}\` | ${f.issue} | ${f.description} |`);
    }
    push('');
  } else {
    push('*No ethical AI findings detected or dev server unavailable.*');
    push('');
  }

  if (conversionAudit?.routeMetrics) {
    const aiPages = conversionAudit.routeMetrics.filter(r => r.ethicalAIScore > 0);
    if (aiPages.length > 0) {
      push('### Ethical AI Signal Coverage');
      push('| Route | Disclosure | Escalation | Jurisdiction | Human Oversight |');
      push('|-------|-----------|-----------|-------------|-----------------|');
      for (const r of aiPages) {
        const s = r.ethicalAISignals || [];
        push(`| \`${r.route}\` | ${s.includes('ai-disclosure') ? 'Yes' : 'No'} | ${s.includes('escalation-path') ? 'Yes' : 'No'} | ${s.includes('jurisdiction-warning') ? 'Yes' : 'No'} | ${s.includes('human-oversight') ? 'Yes' : 'No'} |`);
      }
      push('');
    }
  }
  push(hr);

  // H. Accessibility Findings
  push('## H. Accessibility Findings (WCAG 2.1 AA)');
  push('');

  if (a11yAudit && a11yAudit.totalFindings > 0) {
    push(`Total violations: ${a11yAudit.totalFindings}`);
    push('');
    push('### By Issue Type');
    push('| Issue | Count | Impact |');
    push('|-------|-------|--------|');
    if (a11yAudit.byIssueType) {
      for (const [issue, count] of a11yAudit.byIssueType.slice(0, 20)) {
        const sample = a11yAudit.findings.find(f => f.issue === issue);
        push(`| ${issue} | ${count} | ${sample?.severity || ''} |`);
      }
    }
    push('');

    push('### Detailed Violations (top 20)');
    for (const f of (a11yAudit.findings || []).slice(0, 20)) {
      push(`- [${f.severity.toUpperCase()}] \`${f.route}\` - **${f.issue}**: ${f.description?.slice(0, 120) || ''}`);
      if (f.selector) push(`  - Selector: \`${f.selector}\``);
      if (f.helpUrl) push(`  - Help: ${f.helpUrl}`);
    }
    push('');
  } else {
    push('*No accessibility violations detected or dev server unavailable.*');
    push('');
  }
  push(hr);

  // I. Partnership & Revenue Model Analysis
  push('## I. Partnership & Revenue Model Analysis');
  push('');
  push('Assessment of revenue streams observable in the codebase:');
  push('');

  const revenueSignals = {
    'B2C Subscriptions': existsSync(resolve(ROOT, 'src/pages/Pricing.tsx')) ? 'Pricing page exists' : '[evidence unavailable]',
    'SMB Subscriptions': existsSync(resolve(ROOT, 'src/pages/ForBusiness.tsx')) ? 'Business landing page exists' : '[evidence unavailable]',
    'Legal Aid / Pro Bono Licensing': existsSync(resolve(ROOT, 'src/pages/ForOrganizations.tsx')) ? 'Org landing + LSO dashboard exist' : '[evidence unavailable]',
    'Lawyer Referral / Matching': existsSync(resolve(ROOT, 'src/pages/LawyerProfiles.tsx')) ? 'Lawyer profiles + matching system exist' : '[evidence unavailable]',
    'Document Automation': existsSync(resolve(ROOT, 'src/pages/Documents.tsx')) ? 'Document generation pages exist' : '[evidence unavailable]',
    'Checkout / Stripe Integration': existsSync(resolve(ROOT, 'supabase/functions/stripe-checkout-session/index.ts')) ? 'Stripe edge functions deployed' : '[evidence unavailable]',
    'Partner Channel': existsSync(resolve(ROOT, 'src/pages/PartnerHub.tsx')) ? 'Partner hub + pipeline system exist' : '[evidence unavailable]',
  };

  push('| Revenue Stream | Evidence |');
  push('|---------------|----------|');
  for (const [stream, evidence] of Object.entries(revenueSignals)) {
    push(`| ${stream} | ${evidence} |`);
  }
  push('');
  push('**[inference]** The codebase supports multiple revenue streams. Conversion optimization should focus on the B2C individual and SMB signup funnels as these have the highest volume potential.');
  push(hr);

  // J. Prioritized Remediation Backlog
  push('## J. Prioritized Remediation Backlog');
  push('');
  push('Ordered by severity then frequency:');
  push('');

  let backlogNum = 1;
  if (bySeverity.critical.length > 0) {
    push('### Critical (Fix within 24h)');
    const grouped = groupByIssue(bySeverity.critical);
    for (const [issue, items] of grouped.slice(0, 10)) {
      push(`${backlogNum}. **${issue}** (${items.length} instances) - Routes: ${[...new Set(items.map(i => i.route))].slice(0, 5).map(r => `\`${r}\``).join(', ')}`);
      backlogNum++;
    }
    push('');
  }

  if (bySeverity.high.length > 0) {
    push('### High (Fix within 1 week)');
    const grouped = groupByIssue(bySeverity.high);
    for (const [issue, items] of grouped.slice(0, 15)) {
      push(`${backlogNum}. **${issue}** (${items.length} instances) - Routes: ${[...new Set(items.map(i => i.route))].slice(0, 5).map(r => `\`${r}\``).join(', ')}`);
      backlogNum++;
    }
    push('');
  }

  if (bySeverity.medium.length > 0) {
    push('### Medium (Fix within 2 weeks)');
    const grouped = groupByIssue(bySeverity.medium);
    for (const [issue, items] of grouped.slice(0, 10)) {
      push(`${backlogNum}. **${issue}** (${items.length} instances)`);
      backlogNum++;
    }
    push('');
  }

  if (bySeverity.low.length > 0) {
    push('### Low (Next sprint)');
    const grouped = groupByIssue(bySeverity.low);
    for (const [issue, items] of grouped.slice(0, 10)) {
      push(`${backlogNum}. **${issue}** (${items.length} instances)`);
      backlogNum++;
    }
    push('');
  }
  push(hr);

  // K. Best-in-Class Assessment
  push('## K. Best-in-Class Assessment');
  push('');
  push('Heuristic scoring against industry-leading legaltech platforms:');
  push('');

  const criteria = [
    { name: 'Value Proposition Clarity', max: 10, score: domInventory?.pages?.[0]?.inventory?.ctas?.length > 0 ? 7 : 3, note: domInventory?.pages?.[0]?.inventory ? '[inference] Based on homepage CTA presence' : '[evidence unavailable]' },
    { name: 'Speed to User Outcome', max: 10, score: 6, note: '[inference] Multiple entry points exist but flow depth varies' },
    { name: 'Trust Building', max: 10, score: conversionAudit?.summary?.avgTrustSignals > 2 ? 8 : 5, note: `Avg trust signals: ${conversionAudit?.summary?.avgTrustSignals || '[evidence unavailable]'}` },
    { name: 'Mobile Readiness', max: 10, score: (visualAudit?.findings?.filter(f => f.issue === 'layout-overflow' && f.viewport === 'mobile')?.length || 0) < 5 ? 8 : 5, note: `${visualAudit?.findings?.filter(f => f.issue === 'layout-overflow' && f.viewport === 'mobile')?.length || 0} mobile overflow issues` },
    { name: 'Accessibility (WCAG 2.1 AA)', max: 10, score: (a11yAudit?.totalFindings || 0) < 10 ? 8 : (a11yAudit?.totalFindings || 0) < 50 ? 6 : 4, note: `${a11yAudit?.totalFindings || 0} total violations` },
    { name: 'Localization Readiness', max: 10, score: (routeInventory?.routes?.filter(r => r.icp === 'spanish-speaking')?.length || 0) > 0 ? 6 : 2, note: `${routeInventory?.routes?.filter(r => r.icp === 'spanish-speaking')?.length || 0} Spanish routes` },
    { name: 'Ethical AI Compliance', max: 10, score: conversionAudit?.summary?.avgEthicalAIScore > 2 ? 8 : 5, note: `Avg score: ${conversionAudit?.summary?.avgEthicalAIScore || '[evidence unavailable]'}/4` },
    { name: 'Operational Credibility', max: 10, score: 7, note: '[inference] Trust center, SLA page, governance pages present in route inventory' },
  ];

  push('| Criterion | Score | Max | Notes |');
  push('|-----------|-------|-----|-------|');
  let totalScore = 0;
  let totalMax = 0;
  for (const c of criteria) {
    push(`| ${c.name} | ${c.score} | ${c.max} | ${c.note} |`);
    totalScore += c.score;
    totalMax += c.max;
  }
  push(`| **TOTAL** | **${totalScore}** | **${totalMax}** | **${Math.round(totalScore / totalMax * 100)}%** |`);
  push('');
  push(`**Assessment:** ${totalScore / totalMax >= 0.7 ? 'Strong foundation with targeted improvements needed' : totalScore / totalMax >= 0.5 ? 'Solid base requiring significant polish' : 'Major gaps require attention before launch'}`);
  push(hr);

  // L. Evidence Appendix
  push('## L. Evidence Appendix');
  push('');
  push('### Audit Artifacts');
  push('| File | Description |');
  push('|------|-------------|');
  push(`| \`${config.outputDir}/route-inventory.json\` | All discovered routes with ICP mapping |`);
  push(`| \`${config.outputDir}/visual-audit.json\` | Layout and visual findings |`);
  push(`| \`${config.outputDir}/page-dom-inventory.json\` | Full DOM inventory per page |`);
  push(`| \`${config.outputDir}/accessibility-audit.json\` | axe-core WCAG violations |`);
  push(`| \`${config.outputDir}/content-audit.json\` | Reading level and jargon metrics |`);
  push(`| \`${config.outputDir}/conversion-audit.json\` | CTA, trust, and ethical AI metrics |`);
  push(`| \`${config.outputDir}/screenshots/\` | Full-page screenshots per route per viewport |`);
  push('');
  push('### Configuration');
  push('```json');
  push(JSON.stringify({ viewports: config.viewports, contentThresholds: config.contentThresholds, conversionThresholds: config.conversionThresholds }, null, 2));
  push('```');
  push('');
  push('### How to Re-run');
  push('```bash');
  push('# Audit local dev server (requires server running on localhost:5173)');
  push('npm run audit:all:local');
  push('');
  push('# Audit live site');
  push('npm run audit:all:live');
  push('```');
  push('');
  push(hr);
  push('');
  push('*Report generated by ezLegal.ai Automated Audit System v2.0*');
  push(`*Audited ${routeInventory?.totalRoutes || 0} routes across ${Object.keys(config.viewports).length} viewports for ${config.icpDefinitions.length} ICPs*`);

  return lines.join('\n');
}

function groupByIssue(findings) {
  const grouped = findings.reduce((acc, f) => {
    const key = f.issue || f.description?.slice(0, 40) || 'unknown';
    acc[key] = acc[key] || [];
    acc[key].push(f);
    return acc;
  }, {});
  return Object.entries(grouped).sort((a, b) => b[1].length - a[1].length);
}

